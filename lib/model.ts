// Token Radar model (radar-2): one sealed snapshot in, one ranked board out.
//
// The board ranks every protocol on the snapshot's watchlist (the floor) plus
// every other rankable pre-token protocol below the floor — 226 rows in this
// snapshot. A protocol is rankable when the snapshot records no token for it
// (no market cap, no CoinGecko id, no symbol), it is not an exchange, and its
// name carries no version marker. Protocols the house rule sets aside —
// wrapped, staked or bridged products of a token that already trades — are
// listed separately as "set aside" with the reason, never ranked as pre-token.
//
// Implied value follows only from the snapshot's own figures:
//
//   implied = tvl_usd
//           x category_multiple   (what a token in this category is worth
//                                  per dollar of TVL, from the market's own
//                                  FDV/TVL priors, stated in the table below)
//           x growth_multiplier   (1 + clamp(change_7d, -60, 150) / 100 x 0.6)
//           x maturity_multiplier (0.55 + min(age_days, 1460) / 1460 x 0.45;
//                                  age unknown: 365 days)
//           x chain_multiplier    (1 + 0.03 x min(chains - 1, 5))
//
// No protocol name is ever special-cased: the same function scores every row,
// and the dashboard recomputes each row from the same figures so the page and
// board.json always agree.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them. */
